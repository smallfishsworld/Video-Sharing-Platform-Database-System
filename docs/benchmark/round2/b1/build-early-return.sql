-- Schema of the video-sharing platform (PostgreSQL 15 or newer).
--
-- Conventions
--   * Every relationship table is keyed by (object, user), so "has user U liked video V?" is a
--     primary-key lookup. The reverse direction (everything a user did) has a covering
--     (user, object) index, so both directions can be answered by index-only scans.
--   * Foreign keys cascade on delete: deleting a user or a video removes everything that
--     references it inside the same statement, so no orphan rows can be left behind.
--   * Real-valued data (durations, view times, danmu times) is double precision so that sums and
--     averages are not accumulated in float4.
--   * The bulk importer (BulkImporter) drops the indexes, foreign keys and derived_* triggers
--     defined here before loading and recreates them from the catalog afterwards, so this file
--     stays the single source of truth for the schema.

create table users (
    mid      bigint generated by default as identity primary key,
    name     varchar  not null,
    sex      varchar,
    birthday varchar,
    level    smallint not null default 0,
    coin     integer  not null default 0 check (coin >= 0),
    sign     varchar,
    identity varchar  not null default 'USER' check (identity in ('USER', 'SUPERUSER')),
    password varchar  not null,
    -- Optional OIDC identities. An empty value is stored as NULL, so uniqueness only applies to
    -- users who actually have one.
    qq       varchar unique,
    wechat   varchar unique
);

create table videos (
    bv          varchar primary key,
    title       varchar          not null,
    owner_mid   bigint           not null references users (mid) on delete cascade,
    owner_name  varchar          not null,
    commit_time timestamp        not null,
    -- Both review columns are NULL until a superuser reviews the video.
    review_time timestamp,
    reviewer    bigint references users (mid) on delete set null,
    -- NULL means the video has no embargo: it is public as soon as it is reviewed.
    public_time timestamp,
    duration    double precision not null,
    description varchar,
    -- The titles of one owner's videos are unique; this index also serves owner_mid lookups.
    unique (owner_mid, title)
);
create index videos_reviewer_idx on videos (reviewer);

-- follower_mid follows followee_mid.
create table followings (
    follower_mid bigint not null references users (mid) on delete cascade,
    followee_mid bigint not null references users (mid) on delete cascade,
    primary key (follower_mid, followee_mid)
);
create index followings_followee_idx on followings (followee_mid, follower_mid);

create table viewers (
    bv        varchar          not null references videos (bv) on delete cascade,
    mid       bigint           not null references users (mid) on delete cascade,
    view_time double precision not null,
    primary key (bv, mid)
);
create index viewers_mid_idx on viewers (mid, bv);

create table videolikes (
    bv  varchar not null references videos (bv) on delete cascade,
    mid bigint  not null references users (mid) on delete cascade,
    primary key (bv, mid)
);
create index videolikes_mid_idx on videolikes (mid, bv);

create table coins (
    bv  varchar not null references videos (bv) on delete cascade,
    mid bigint  not null references users (mid) on delete cascade,
    primary key (bv, mid)
);
create index coins_mid_idx on coins (mid, bv);

create table favorites (
    bv  varchar not null references videos (bv) on delete cascade,
    mid bigint  not null references users (mid) on delete cascade,
    primary key (bv, mid)
);
create index favorites_mid_idx on favorites (mid, bv);

create table danmus (
    id        bigint generated by default as identity primary key,
    bv        varchar          not null references videos (bv) on delete cascade,
    mid       bigint           not null references users (mid) on delete cascade,
    -- Seconds since the start of the video.
    time      double precision not null,
    content   varchar          not null,
    post_time timestamp        not null
);
create index danmus_bv_time_idx on danmus (bv, time);
create index danmus_mid_idx on danmus (mid);

create table danmulikes (
    danmu_id bigint not null references danmus (id) on delete cascade,
    mid      bigint not null references users (mid) on delete cascade,
    primary key (danmu_id, mid)
);
create index danmulikes_mid_idx on danmulikes (mid);

-- Number of non-overlapping occurrences of needle in haystack (case-sensitive; callers fold both
-- sides with fold_case). replace() removes occurrences left to right, exactly like a greedy scan.
create function count_occurrences(haystack text, needle text) returns integer
    language sql immutable strict parallel safe
    return (length(haystack) - length(replace(haystack, needle, ''))) / length(needle);

-- Lowercases with the ICU root locale, so case-insensitive search folds every script the same way
-- whatever the database locale is (lower() under LC_CTYPE=C folds only ASCII). Needs a server
-- built with ICU, which the PostgreSQL packages and the official Docker images are.
create function fold_case(t text) returns text
    language sql immutable strict parallel safe
    return lower(t collate "und-x-icu");

-- Derived data -----------------------------------------------------------------------------------
--
-- Two tables cache aggregates that the read paths would otherwise recompute from hundreds of
-- thousands of rows on every call. Statement-level triggers (all named derived_*) keep them exact
-- inside the writing transaction: they read the affected rows from transition tables, so a
-- statement costs one set-based update no matter how many rows it touches. Each trigger updates
-- its rows in key order, so two firings of one trigger lock the counters they share in the same
-- order. That order holds within one firing only: a DELETE that cascades fires one trigger per
-- cascaded table, so two concurrent cascading deletes (two accounts, or a video and one of its
-- likers) can still lock in crossing orders and deadlock. The services retry a write that loses a
-- deadlock (support/Writes.java).
--
-- TRUNCATE fires no row triggers: truncate the derived tables together with their sources (the
-- service's truncate() truncates every table). BulkImporter drops the derived_* triggers while it
-- loads, writes both tables from the loaded data, and recreates the triggers.

-- Per-video counters used by the recommendations, the search ranking and the view rate. They have
-- no CHECK (>= 0) constraints because the triggers apply signed deltas with INSERT ... ON
-- CONFLICT DO UPDATE, and PostgreSQL checks the proposed (negative) row before it finds the
-- conflict; the integration tests compare the counters with a full recomputation instead.
create table video_stats (
    bv            varchar primary key references videos (bv) on delete cascade,
    viewers       integer          not null default 0,
    view_time_sum double precision not null default 0,
    likes         integer          not null default 0,
    coins         integer          not null default 0,
    favorites     integer          not null default 0,
    danmus        integer          not null default 0
);

-- For every ordered pair of distinct videos that share at least one viewer: the number of users
-- who watched both. Both directions are stored, so the neighbours of a video are one index range.
create table video_coviews (
    bv       varchar not null references videos (bv) on delete cascade,
    other_bv varchar not null references videos (bv) on delete cascade,
    viewers  integer not null check (viewers > 0),
    primary key (bv, other_bv)
);
create index video_coviews_other_bv_idx on video_coviews (other_bv);

create function derived_videos() returns trigger
    language plpgsql as
$$
begin
    insert into video_stats (bv)
    select bv from new_rows order by bv
    on conflict do nothing;
    return null;
end
$$;

create trigger derived_videos_insert
    after insert on videos referencing new table as new_rows
    for each statement execute function derived_videos();

-- One counter per interaction table; tg_table_name selects it. Every change is a single upsert of
-- signed deltas sorted by bv: ON CONFLICT locks the counter rows in that order, so two upserts
-- that touch the same videos take their row locks in the same order (see the deadlock note
-- above for cascades). Rows of videos that no longer exist (a video being deleted cascades to its
-- interactions) are skipped; their counters go with them.
create function derived_interactions() returns trigger
    language plpgsql as
$$
declare
    first_bv varchar;
begin
    if tg_op = 'INSERT' then
        if not exists (select from new_rows) then
            return null;
        end if;
        insert into video_stats as s (bv, likes, coins, favorites, danmus)
        select bv,
               case when tg_table_name = 'videolikes' then count(*) else 0 end,
               case when tg_table_name = 'coins' then count(*) else 0 end,
               case when tg_table_name = 'favorites' then count(*) else 0 end,
               case when tg_table_name = 'danmus' then count(*) else 0 end
        from new_rows
        group by bv
        order by bv
        on conflict (bv) do update
        set likes     = s.likes + excluded.likes,
            coins     = s.coins + excluded.coins,
            favorites = s.favorites + excluded.favorites,
            danmus    = s.danmus + excluded.danmus;
    elsif tg_op = 'DELETE' then
        select o.bv into first_bv from old_rows o limit 1;
        if first_bv is null then
            return null;
        end if;
        -- A cascade from a deleted video: its counters go with it.
        if not exists (select from videos where bv = first_bv) and not exists (select from old_rows where bv <> first_bv) then
            return null;
        end if;
        insert into video_stats as s (bv, likes, coins, favorites, danmus)
        select o.bv,
               case when tg_table_name = 'videolikes' then -count(*) else 0 end,
               case when tg_table_name = 'coins' then -count(*) else 0 end,
               case when tg_table_name = 'favorites' then -count(*) else 0 end,
               case when tg_table_name = 'danmus' then -count(*) else 0 end
        from old_rows o
        join videos v on v.bv = o.bv
        group by o.bv
        order by o.bv
        on conflict (bv) do update
        set likes     = s.likes + excluded.likes,
            coins     = s.coins + excluded.coins,
            favorites = s.favorites + excluded.favorites,
            danmus    = s.danmus + excluded.danmus;
    else
        insert into video_stats as s (bv, likes, coins, favorites, danmus)
        select c.bv,
               case when tg_table_name = 'videolikes' then sum(c.delta) else 0 end,
               case when tg_table_name = 'coins' then sum(c.delta) else 0 end,
               case when tg_table_name = 'favorites' then sum(c.delta) else 0 end,
               case when tg_table_name = 'danmus' then sum(c.delta) else 0 end
        from (select bv, -1 as delta from old_rows union all select bv, 1 from new_rows) c
        join videos v on v.bv = c.bv
        group by c.bv
        order by c.bv
        on conflict (bv) do update
        set likes     = s.likes + excluded.likes,
            coins     = s.coins + excluded.coins,
            favorites = s.favorites + excluded.favorites,
            danmus    = s.danmus + excluded.danmus;
    end if;
    return null;
end
$$;

