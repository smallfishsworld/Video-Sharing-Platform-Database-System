-- Viewer counters and co-view counts. A user who watches both a and b contributes one to the
-- pairs (a, b) and (b, a); the deltas below are exactly the pairs that gain or lose such a user.
--
-- The pair deltas are computed from the user's other views, so two transactions that change views
-- of the same user at the same time must not both compute them from a snapshot that misses the
-- other's rows (each would miss the pairs between its view and the other's, and those pairs would
-- be lost or decremented twice). Before computing pairs, the trigger therefore locks the users
-- rows of the affected viewers, in mid order, as a statement of its own: FOR NO KEY UPDATE
-- conflicts with itself but not with the KEY SHARE locks of foreign-key checks, and the pair
-- statement that follows takes a new snapshot that includes every committed change of those
-- users' views. The users rows are locked before any counter row, the same order as a coin
-- donation (users, then video_stats).
create function derived_viewers() returns trigger
    language plpgsql as
$$
declare
    kept_bv        varchar[];
    kept_n         integer[];
    kept_view_time double precision[];
    pair_bv        varchar[];
    pair_other     varchar[];
    pair_lost      integer[];
    first_bv       varchar;
begin
    if tg_op = 'UPDATE' then
        -- Only view_time may change: a new (bv, mid) is a different viewer.
        if exists (select bv, mid from old_rows except select bv, mid from new_rows) then
            raise exception 'the (bv, mid) key of a viewers row cannot be updated; delete and insert it instead'
                using errcode = 'feature_not_supported';
        end if;
        insert into video_stats as s (bv, view_time_sum)
        select bv, sum(view_time)
        from (select bv, view_time from new_rows union all select bv, -view_time from old_rows) t
        group by bv
        order by bv
        on conflict (bv) do update set view_time_sum = s.view_time_sum + excluded.view_time_sum;
        return null;
    end if;

    if tg_op = 'INSERT' then
        perform from users u
        where u.mid in (select distinct mid from new_rows)
        order by u.mid
        for no key update of u;

        insert into video_stats as s (bv, viewers, view_time_sum)
        select bv, count(*), sum(view_time) from new_rows group by bv order by bv
        on conflict (bv) do update
        set viewers = s.viewers + excluded.viewers, view_time_sum = s.view_time_sum + excluded.view_time_sum;

        -- New pairs: (new, any current viewing) plus (old viewing, new).
        insert into video_coviews as c (bv, other_bv, viewers)
        select bv, other_bv, count(*)
        from (select n.bv, w.bv as other_bv
              from new_rows n join viewers w on w.mid = n.mid and w.bv <> n.bv
              union all
              select w.bv, n.bv
              from new_rows n join viewers w on w.mid = n.mid and w.bv <> n.bv
              where not exists (select 1 from new_rows x where x.bv = w.bv and x.mid = w.mid)) p
        group by bv, other_bv
        order by bv, other_bv
        on conflict (bv, other_bv) do update set viewers = c.viewers + excluded.viewers;
        return null;
    end if;

    -- DELETE. Counters are adjusted only for videos that still exist: when a video is deleted, its
    -- viewers go by cascade and its derived rows go with it, so there is nothing to maintain. The
    -- view time sum restarts from exactly 0 when the last viewer goes, so rounding errors of
    -- earlier subtractions do not outlive the viewers they came from.
    select o.bv into first_bv from old_rows o limit 1;
    if first_bv is null then
        return null;
    end if;
    if not exists (select from videos where bv = first_bv) and not exists (select from old_rows where bv <> first_bv) then
        return null;
    end if;

    select array_agg(d.bv order by d.bv), array_agg(d.n order by d.bv), array_agg(d.view_time order by d.bv)
    into kept_bv, kept_n, kept_view_time
    from (select bv, count(*)::integer as n, sum(view_time) as view_time from old_rows group by bv) d
    join videos v on v.bv = d.bv;
    if kept_bv is null then
        return null;
    end if;

    -- A deleted user's row is already locked by the DELETE and is invisible here.
    perform from users u
    where u.mid in (select distinct o.mid from old_rows o where o.bv = any (kept_bv))
    order by u.mid
    for no key update of u;

    insert into video_stats as s (bv, viewers, view_time_sum)
    select bv, -n, -view_time from unnest(kept_bv, kept_n, kept_view_time) as d (bv, n, view_time)
    order by bv
    on conflict (bv) do update
    set viewers       = s.viewers + excluded.viewers,
        view_time_sum = case when s.viewers + excluded.viewers = 0 then 0
                             else s.view_time_sum + excluded.view_time_sum end;

    -- Lost pairs: (deleted, remaining), (remaining, deleted) and (deleted, deleted).
    with gone as (
        select o.bv, o.mid from old_rows o where o.bv = any (kept_bv)
    ),
    shared as (
        select g.bv as a, w.bv as b from gone g join viewers w on w.mid = g.mid
    )
    select array_agg(bv order by bv, other_bv),
           array_agg(other_bv order by bv, other_bv),
           array_agg(lost order by bv, other_bv)
    into pair_bv, pair_other, pair_lost
    from (select bv, other_bv, count(*)::integer as lost
          from (select a as bv, b as other_bv from shared
                union all
                select b, a from shared
                union all
                select g.bv, g2.bv from gone g join gone g2 on g2.mid = g.mid and g2.bv <> g.bv) p
          group by bv, other_bv) l;

    if pair_bv is not null then
        perform from video_coviews c
        join unnest(pair_bv, pair_other) as p (bv, other_bv) on c.bv = p.bv and c.other_bv = p.other_bv
        order by c.bv, c.other_bv
        for update of c;
        delete from video_coviews c
        using unnest(pair_bv, pair_other, pair_lost) as p (bv, other_bv, lost)
        where c.bv = p.bv and c.other_bv = p.other_bv and c.viewers <= p.lost;
        update video_coviews c
        set viewers = c.viewers - p.lost
        from unnest(pair_bv, pair_other, pair_lost) as p (bv, other_bv, lost)
        where c.bv = p.bv and c.other_bv = p.other_bv;
    end if;
    return null;
end
$$;

