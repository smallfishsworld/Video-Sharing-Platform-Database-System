#!/usr/bin/env python3
"""Markdown tables of the round-3 and round-4 WriteBench runs, as in docs/benchmark/round{3,4}/writebench/summary.md.

    python3 scripts/writebench/tables3.py [DIR]     # DIR defaults to docs/benchmark/round3/writebench

Runs by label: delacct-{orig,new}-c8-r<i> and delacct-r2-c8-r1 (deleteAccount on 8 clients),
delvid-r2-c8-r1 (the round-2 jar's video deletions on 8 clients), steady-{orig,new}-c{1,8}-r<i>,
count-new, stress-{orig,new}, and diag-{orig,r2}-c8 (8-client runs with --sample: pg_stat_activity and
/proc CPU sampling). Each <label>.deadlocks.txt holds pg_stat_database.deadlocks before and after
the run. Figures over several runs are medians of the per-run figures, [smallest–largest run].
"orig" is the original implementation, "r2" this project at the end of round 2 (a330c0c, jar
42004a16), "new" this version.
"""
import glob
import json
import os
import re
import statistics
import sys

D = sys.argv[1] if len(sys.argv) > 1 else "docs/benchmark/round3/writebench"
ROUND = next((c for c in reversed(os.path.abspath(D).split(os.sep)) if re.fullmatch(r"round\d+", c)), "round 3")
ROUND = ROUND.replace("round", "round ")
# Jars whose build commit differs from the code_sha label of their runs.
JAR_BUILT_FROM = {"bcde4e16d804": "1717da9", "b7c1f99e88d1": "b5bbd84"}
OPS = ["sendDanmu", "likeDanmu", "coinVideo", "likeVideo", "collectVideo", "postVideo", "register",
       "updateVideoInfo", "reviewVideo", "deleteVideo", "deleteVideoWithViews", "deleteAccount", "follow"]
lines = []
P = lines.append


def runs(pattern):
    return [json.load(open(f)) for f in sorted(glob.glob(os.path.join(D, pattern + ".json")))]


def deadlocks(pattern):
    n = []
    for f in sorted(glob.glob(os.path.join(D, pattern + ".deadlocks.txt"))):
        t = open(f).read()
        if "deadlocks_detected_during_run=" in t:
            n.append(int(t.split("deadlocks_detected_during_run=")[1].split()[0]))
    return n


def cell(v, digits=2):
    if not v:
        return "–"
    f = f"{{:,.{digits}f}}"
    if len(v) == 1:
        return f.format(v[0])
    return f"{f.format(statistics.median(v))} [{f.format(min(v))}–{f.format(max(v))}]"


def op_results(rs, op):
    return [x for r in rs for x in r["results"] if x["op"] == op and x["calls"]]


def jars(rs):
    out = set()
    for r in rs:
        o = r["options"]
        jar = o.get("jar_sha256", "")[:12]
        built = f", built from {JAR_BUILT_FROM[jar]}" if jar in JAR_BUILT_FROM else ""
        out.add(f"({o.get('code_sha', '')[:7]}, jar {jar}{built})")
    return ", ".join(sorted(out))


def paired(a, b):
    """Per-run ratios b/a of runs paired by order (r1 with r1, ...), and whether the two ranges overlap."""
    if not a or not b:
        return "–"
    pairs = "/".join(f"{y / x:.2f}" for x, y in zip(a, b))
    if len(a) < 2 or len(b) < 2:
        return f"{pairs}, one run"
    marker = "overlap" if max(a) >= min(b) and max(b) >= min(a) else "disjoint"
    return f"{pairs}, {marker}"


def failures(xs):
    out = []
    for x in xs:
        why = ", ".join(x.get("errors", {}) or {})
        out.append(f"{x['failed']}" + (f" ({why})" if why else ""))
    return "[" + ", ".join(out) + "]"


every = [json.load(open(f)) for f in glob.glob(os.path.join(D, "*.json"))]
P(f"# WriteBench, {ROUND}\n")
P("Generated by `python3 scripts/writebench/tables3.py` from the runs in this directory; each `<label>.json` "
  "holds the run's options, jar sha256, commit and boot, `<label>.log` its output and `<label>.deadlocks.txt` "
  "the deadlocks the server detected during the run (pg_stat_database). WriteBench and its modes are described "
  "in `scripts/writebench/WriteBench.java`; round 2's runs are in `docs/benchmark/round2/writebench`. From round 4 "
  "on, each JSON also records git HEAD and the porcelain status of the checkout and the SHA-256 and repository HEAD "
  "of every SQL file, taken inside the lock (`git_head`, `git_porcelain`, `sql_sha256`, `sql_git`); before, "
  "`code_sha` is the only commit, a label chosen by the caller.\n")
P("Original = the 2023 implementation (the course submission on main); round 2 = this project at a330c0c (jar "
  "42004a16); this version = the code named below. Every run holds `/home/user/work/bench.lock`; several runs share one "
  "hold (at most 15 minutes), with the original and this version alternating inside it. Steady runs use `--settle` "
  "(a `CHECKPOINT` after the import); deleteVideoWithViews deletes 8 imported videos (about 20,000 views each).\n")
if os.path.isdir(os.path.join(D, "1717da9")):
    P("The runs of the first version of the round-3 fix (1717da9, whose co-view trigger scanned the whole co-view "
      "table on every deletion) are in `1717da9/`, summarized by `python3 scripts/writebench/tables3.py "
      "docs/benchmark/round3/writebench/1717da9`.\n")
boots = sorted({r["options"].get("boot", "") for r in every} - {""})
P("Every run was on the same boot (`uptime -s` gave the same time for all of them; each run's JSON records it)."
  if len(boots) == 1 else f"The runs span {len(boots)} boots (`uptime -s`; each run's JSON records its boot).")

# Deletions on 8 clients ---------------------------------------------------------------------------
P("\n## Deletions on 8 clients\n")
P("deleteAccount: 100 measured calls per run after 20 warm-up calls, each deleting a different imported user "
  "who owns no video. deleteVideoWithViews: the 8 deletions of imported videos of each 8-client steady run. "
  "p50 / p95 / p99 / max in ms per call.\n")
P("| operation | version | runs | p50 | p95 | p99 | max | throughput /s | failed calls per run | deadlocks detected per run |")
P("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
for op, pats in (("deleteAccount", (("original", "delacct-orig-c8-r*"), ("round 2", "delacct-r2-c8-r*"),
                                     ("this version", "delacct-new-c8-r*"))),
                 ("deleteVideoWithViews", (("original", "steady-orig-c8-r*"), ("round 2", "delvid-r2-c8-r*"),
                                            ("this version", "steady-new-c8-r*"))),
                 ("deleteVideo", (("original", "steady-orig-c8-r*"), ("this version", "steady-new-c8-r*")))):
    for label, pat in pats:
        xs = op_results(runs(pat), op)
        if not xs:
            continue
        P(f"| {op} | {label} | {len(xs)} | {cell([x['p50_ms'] for x in xs])} | {cell([x['p95_ms'] for x in xs])} | "
          f"{cell([x['p99_ms'] for x in xs if 'p99_ms' in x])} | {cell([x['max_ms'] for x in xs], 0)} | "
          f"{cell([x['throughput_per_s'] for x in xs], 1)} | {failures(xs)} | {deadlocks(pat)} |")
if runs("delacct-r2-c8-r*") or runs("delvid-r2-c8-r*"):
    P("\nThe round-2 runs here use the jar of a330c0c (42004a16) and its SQL; `delvid-r2-c8-r1` runs only the two "
      "video deletions, so its deleteVideo calls find no posted video to delete and are left out. Round 2's own runs "
      "(docs/benchmark/round2/writebench, 3 and 5 runs, no p99 recorded) are in that summary.")

# Steady state ---------------------------------------------------------------------------------------
for clients in (8, 1):
    o, n = runs(f"steady-orig-c{clients}-r*"), runs(f"steady-new-c{clients}-r*")
    if not (o or n):
        continue
    P(f"\n## Steady state, {clients} client{'s' if clients > 1 else ''}: {len(o)} run{'s' if len(o) != 1 else ''} "
      f"of the original, {len(n)} of this version\n")
    P(f"Code (code_sha label, jar sha256 prefix): original {jars(o)}; this version {jars(n)}. The label names the "
      "commit of the SQL that run.sh applied; a jar built from an earlier commit has the same Java code. 300 warm-up "
      "and 600 measured calls per operation. p50 / p99 in ms per call, throughput in calls per second. The ratio is "
      "a ratio of the medians; the paired column divides the runs in order (r1 by r1, ...) and says whether the "
      "two versions' throughput ranges overlap.\n")
    P("| operation | p50 original | p50 this version | p99 original | p99 this version | throughput original | "
      "throughput this version | this version / original (throughput) | paired, overlap |")
    P("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for op in OPS:
        a, b = op_results(o, op), op_results(n, op)
        if not (a or b):
            continue
        ta, tb = [x["throughput_per_s"] for x in a], [x["throughput_per_s"] for x in b]
        ratio = f"{statistics.median(tb) / statistics.median(ta):.2f}" if ta and tb else "–"
        P(f"| {op} | {cell([x['p50_ms'] for x in a])} | {cell([x['p50_ms'] for x in b])} | "
          f"{cell([x['p99_ms'] for x in a])} | {cell([x['p99_ms'] for x in b])} | {cell(ta, 0)} | {cell(tb, 0)} | {ratio} | "
          f"{paired(ta, tb)} |")
    fails = [f"{lab} {x['op']}: {x['failed']} of {x['calls']}" for lab, rs in (("original", o), ("this version", n))
             for r in rs for x in r["results"] if x.get("failed")]
    P("\nFailed calls: " + ("; ".join(fails) if fails else "none") + ".")
    P(f"Deadlocks detected per run: original {deadlocks(f'steady-orig-c{clients}-r*')}, "
      f"this version {deadlocks(f'steady-new-c{clients}-r*')}.")

# Diagnosis --------------------------------------------------------------------------------------------
dg = {v: runs(f"diag-{v}-c8") for v in ("orig", "r2")}
if all(dg.values()):
    P("\n## Where the 8-client time goes (diagnosis runs)\n")
    P("One 8-client steady run each of the original and of round 2 with `--sample`: about every 2 ms, a separate "
      "connection counts what the database's other client backends are doing (`state`, or the `wait_event` of an "
      "active backend, `CPU` when it waits on nothing); per call, the CPU time of those backends and of the "
      "WriteBench JVM (`/proc/<pid>/stat`). The sampling itself costs throughput, so these runs are for "
      "attribution only. Backends per sample: of the pool's 10 connections, 8 are in use; `idle` includes the "
      "client-side part of each call. The machine has 4 vCPUs. The JVM's CPU time is that of the whole WriteBench "
      "process (/proc/self), so it includes the sampler's thread; the machine's other processes are left out.\n")
    P("| operation | version | throughput /s | backend CPU ms/call | JVM CPU ms/call | vCPUs busy ((backend + JVM CPU) × throughput) | waiting for WAL flush (LWLock:WALWrite + IO:WALSync) | on CPU | row locks (Lock:transactionid + Lock:tuple) | idle |")
    P("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for op in OPS:
        for v, label in (("orig", "original"), ("r2", "round 2")):
            xs = op_results(dg[v], op)
            if not xs or "sample" not in xs[0]:
                continue
            x = xs[0]
            s = x["sample"]
            w = s["backends_per_sample"]
            wal = w.get("LWLock:WALWrite", 0) + w.get("IO:WALSync", 0)
            rows = w.get("Lock:transactionid", 0) + w.get("Lock:tuple", 0)
            busy = (s["backend_cpu_ms_per_call"] + s["jvm_cpu_ms_per_call"]) * x["throughput_per_s"] / 1000
            P(f"| {op} | {label} | {x['throughput_per_s']:,.0f} | {s['backend_cpu_ms_per_call']} | "
              f"{s['jvm_cpu_ms_per_call']} | {busy:.2f} | {wal:.2f} | {w.get('CPU', 0):.2f} | {rows:.2f} | {w.get('idle', 0):.2f} |")

# Count and stress -------------------------------------------------------------------------------------
cn = runs("count-new")
if cn:
    P("\n## Statements and round trips per call (this version)\n")
    P("Count mode: 20 calls per operation on one thread, server-side prepared statements off.\n")
    P("| operation | statements | round trips |")
    P("|---|---:|---:|")
    for x in cn[0]["results"]:
        P(f"| {x['op']} | {x['statements_per_call']:g} | {x['round_trips_per_call']:g} |")

def toggle(t):
    """A toggle part of the stress mode: trials with failed calls, and lost updates where they can be counted."""
    n = t["trials"]
    if "trials_with_failed_calls" not in t:  # before round 4: one figure for both
        return f"{t['trials_with_lost_update']}/{n} with a failed call or a count mismatch", "–"
    if t.get("trials_with_count_mismatch") is None:
        lost = f"not applicable ({t.get('return_value', '')})"
    else:
        lost = f"{t['trials_with_count_mismatch']} of {t['trials_count_checked']} trials without failed calls"
    return f"{t['trials_with_failed_calls']}/{n}", lost


for v, label in (("orig", "the 2023 implementation"), ("new", "this version")):
    st = runs(f"stress-{v}")
    if not st:
        continue
    r = st[0]["results"]
    c, li, fo, de = r["coin_double_spend"], r["like_toggle"], r["follow_toggle"], r["crossing_account_deletions"]
    e = de.get("errors") or {}
    P(f"\n## Stress ({label})\n")
    if "trials_with_failed_calls" in li:
        how = ("A toggle trial makes 80 calls; it has failed calls if any of them threw, and it is a count mismatch "
               "(a lost update) if, without failed calls, the calls that returned true minus those that returned "
               "false differ from the change of state; that check needs calls that return the new state, which a "
               "sequential probe checks first.")
    else:
        how = ("A toggle trial makes 80 calls. This WriteBench version (before round 4) reported one figure per "
               "toggle part, the trials with a failed call or a count mismatch.")
    P(f"Code: {jars(st)}. 45 trials per part, 8 threads. {how}\n")
    P("| part | trials overspent / with failed calls | lost updates | failed calls | errors | connections left open |")
    P("|---|---:|---|---:|---|---:|")
    P(f"| coin donation | {c['trials_overspent']}/{c['trials']} overspent ({c['trials_with_violation']} with a wrong "
      f"balance; {c['done_donations']} donations done) | – | {c['failed_calls']} | – | {c.get('connections_left_open', 0)} |")
    for name, t in (("like toggle", li), ("follow toggle", fo)):
        failed, lost = toggle(t)
        errs = "; ".join(f"{k}: {n}" for k, n in (t.get("errors") or {}).items()) or "–"
        P(f"| {name} | {failed} | {lost} | {t['failed_calls']} | {errs} | {t.get('connections_left_open', 0)} |")
    P(f"| crossing account deletions | {de['trials_with_error']}/{de['trials']} with an error | – | – | "
      f"{'; '.join(f'{k}: {n}' for k, n in e.items()) or '–'} | {de.get('connections_left_open', 0)} |")
    P(f"\nDeadlocks detected by the server in the crossing deletions: {de['server_deadlocks_detected']}; "
      f"during the whole run: {deadlocks(f'stress-{v}')}.")

print("\n".join(lines))
