-- Schema of the video-sharing platform (PostgreSQL 15 or newer).
--
-- Conventions
--   * Every relationship table is keyed by (object, user), so "has user U liked video V?" is a
--     primary-key lookup. The reverse direction (everything a user did) has a covering
--     (user, object) index, so both directions can be answered by index-only scans.
--   * Foreign keys cascade on delete: deleting a user or a video removes everything that
--     references it inside the same statement, so no orphan rows can be left behind.
--   * Real-valued data (durations, view times, danmu times) is double precision so that sums and
--     averages are not accumulated in float4.
--   * The bulk importer (BulkImporter) drops the indexes and foreign keys defined here before
--     loading and recreates them from the catalog afterwards, so this file stays the single
--     source of truth for the schema.

create table users (
    mid      bigint generated by default as identity primary key,
    name     varchar  not null,
    sex      varchar,
    birthday varchar,
    level    smallint not null default 0,
    coin     integer  not null default 0 check (coin >= 0),
    sign     varchar,
    identity varchar  not null default 'USER' check (identity in ('USER', 'SUPERUSER')),
    password varchar  not null,
    -- Optional OIDC identities. An empty value is stored as NULL, so uniqueness only applies to
    -- users who actually have one.
    qq       varchar unique,
    wechat   varchar unique
);

create table videos (
    bv          varchar primary key,
    title       varchar          not null,
    owner_mid   bigint           not null references users (mid) on delete cascade,
    owner_name  varchar          not null,
    commit_time timestamp        not null,
    -- Both review columns are NULL until a superuser reviews the video.
    review_time timestamp,
    reviewer    bigint references users (mid) on delete set null,
    -- NULL means the video has no embargo: it is public as soon as it is reviewed.
    public_time timestamp,
    duration    double precision not null,
    description varchar,
    -- The titles of one owner's videos are unique; this index also serves owner_mid lookups.
    unique (owner_mid, title)
);
create index videos_reviewer_idx on videos (reviewer);

-- follower_mid follows followee_mid.
create table followings (
    follower_mid bigint not null references users (mid) on delete cascade,
    followee_mid bigint not null references users (mid) on delete cascade,
    primary key (follower_mid, followee_mid)
);
create index followings_followee_idx on followings (followee_mid, follower_mid);

create table viewers (
    bv        varchar          not null references videos (bv) on delete cascade,
    mid       bigint           not null references users (mid) on delete cascade,
    view_time double precision not null,
    primary key (bv, mid)
);
create index viewers_mid_idx on viewers (mid, bv);

create table videolikes (
    bv  varchar not null references videos (bv) on delete cascade,
    mid bigint  not null references users (mid) on delete cascade,
    primary key (bv, mid)
);
create index videolikes_mid_idx on videolikes (mid, bv);

create table coins (
    bv  varchar not null references videos (bv) on delete cascade,
    mid bigint  not null references users (mid) on delete cascade,
    primary key (bv, mid)
);
create index coins_mid_idx on coins (mid, bv);

create table favorites (
    bv  varchar not null references videos (bv) on delete cascade,
    mid bigint  not null references users (mid) on delete cascade,
    primary key (bv, mid)
);
create index favorites_mid_idx on favorites (mid, bv);

create table danmus (
    id        bigint generated by default as identity primary key,
    bv        varchar          not null references videos (bv) on delete cascade,
    mid       bigint           not null references users (mid) on delete cascade,
    -- Seconds since the start of the video.
    time      double precision not null,
    content   varchar          not null,
    post_time timestamp        not null
);
create index danmus_bv_time_idx on danmus (bv, time);
create index danmus_mid_idx on danmus (mid);

create table danmulikes (
    danmu_id bigint not null references danmus (id) on delete cascade,
    mid      bigint not null references users (mid) on delete cascade,
    primary key (danmu_id, mid)
);
create index danmulikes_mid_idx on danmulikes (mid);

-- Number of non-overlapping occurrences of needle in haystack (case-sensitive; callers lower()
-- both sides). replace() removes occurrences left to right, exactly like a greedy scan.
create function count_occurrences(haystack text, needle text) returns integer
    language sql immutable strict parallel safe
    return (length(haystack) - length(replace(haystack, needle, ''))) / length(needle);

